-- =============================================================================
-- VW_PLAYER_360
-- =============================================================================
-- Purpose:    The analytical "Single Player View" for scouting and management.
-- Metrics:   Combines SCD2 player profiles with performance and valuation facts.
-- =============================================================================

USE SCHEMA LIONS_DB.DOMAIN;

CREATE OR REPLACE VIEW VW_PLAYER_360 AS
WITH PLAYER_CORE AS (
    SELECT
        PLAYER_KEY,
        TM_PLAYER_ID,
        PLAYER_NAME,
        POSITION,
        CURRENT_CLUB_NAME,
        MARKET_VALUE_EUR
    FROM DIM_PLAYER
    WHERE IS_CURRENT = TRUE
),

PERFORMANCE_AGG AS (
    SELECT
        PLAYER_KEY,
        SUM(MINUTES_PLAYED) AS TOTAL_MINUTES,
        SUM(GOALS) AS TOTAL_GOALS,
        SUM(ASSISTS) AS TOTAL_ASSISTS,
        SUM(YELLOW_CARDS) AS TOTAL_YELLOWS,
        SUM(RED_CARDS) AS TOTAL_REDS,
        COUNT(MATCH_DATE) AS TOTAL_APPEARANCES,
        (SUM(GOALS) + SUM(ASSISTS)) / NULLIF(SUM(MINUTES_PLAYED), 0) * 90 AS G_A_PER_90,
        SUM(MINUTES_PLAYED) / NULLIF(COUNT(MATCH_DATE), 0) AS AVG_MINUTES_PER_GAME
    FROM FCT_PERFORMANCE
    GROUP BY PLAYER_KEY
),

LATEST_VALUATION AS (
    SELECT
        PLAYER_KEY,
        VALUATION_DELTA_EUR,
        CASE
            WHEN VALUATION_DELTA_EUR > 0 THEN 'UP'
            WHEN VALUATION_DELTA_EUR < 0 THEN 'DOWN'
            ELSE 'STABLE'
        END AS VALUATION_TREND
    FROM FCT_VALUATIONS
    QUALIFY ROW_NUMBER() OVER (PARTITION BY PLAYER_KEY ORDER BY VALUATION_DATE DESC) = 1
)

SELECT
    P.TM_PLAYER_ID,
    P.PLAYER_NAME,
    P.POSITION,
    P.CURRENT_CLUB_NAME,
    P.MARKET_VALUE_EUR,
    V.VALUATION_TREND,
    V.VALUATION_DELTA_EUR AS LATEST_DELTA,
    COALESCE(A.TOTAL_APPEARANCES, 0) AS TOTAL_APPEARANCES,
    COALESCE(A.TOTAL_MINUTES, 0) AS TOTAL_MINUTES,
    COALESCE(A.TOTAL_GOALS, 0) AS TOTAL_GOALS,
    COALESCE(A.TOTAL_ASSISTS, 0) AS TOTAL_ASSISTS,
    ROUND(COALESCE(A.G_A_PER_90, 0), 2) AS G_A_PER_90,
    COALESCE(A.TOTAL_YELLOWS, 0) AS TOTAL_YELLOWS,
    COALESCE(A.TOTAL_REDS, 0) AS TOTAL_REDS,
    CASE
        WHEN P.CURRENT_CLUB_NAME = 'London Lions' THEN 'SQUAD_MEMBER'
        ELSE 'SCOUTING_TARGET'
    END AS SCOUTING_STATUS
FROM PLAYER_CORE AS P
LEFT JOIN PERFORMANCE_AGG AS A ON P.PLAYER_KEY = A.PLAYER_KEY
LEFT JOIN LATEST_VALUATION AS V ON P.PLAYER_KEY = V.PLAYER_KEY;
