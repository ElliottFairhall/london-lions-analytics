USE SCHEMA LIONS_DB.ODS;

CREATE OR REPLACE VIEW VW_ODS_VALUATIONS AS
SELECT
    PLAYER_ID,
    DATE AS VALUATION_DATE,
    MARKET_VALUE_IN_EUR AS MARKET_VALUE_EUR,
    PLAYER_ID || '_' || DATE AS VALUATION_ID,
    MD5(COALESCE(CAST(MARKET_VALUE_IN_EUR AS VARCHAR), '0')) AS NEW_MD5_HASH
FROM LIONS_DB.STAGING.STRM_TM_PLAYER_VALUATIONS
QUALIFY ROW_NUMBER() OVER (PARTITION BY VALUATION_ID ORDER BY METADATA$TS DESC) = 1;
