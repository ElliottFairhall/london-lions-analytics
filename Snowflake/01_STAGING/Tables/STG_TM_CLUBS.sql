USE SCHEMA LIONS_DB.STAGING;

CREATE OR REPLACE TABLE STG_TM_CLUBS (
    CLUB_ID INTEGER,
    CLUB_CODE VARCHAR(100),
    NAME VARCHAR(255),
    DOMESTIC_COMPETITION_ID VARCHAR(20),
    TOTAL_MARKET_VALUE VARCHAR(50),
    SQUAD_SIZE INTEGER,
    AVERAGE_AGE FLOAT,
    FOREIGNERS_NUMBER INTEGER,
    FOREIGNERS_PERCENTAGE FLOAT,
    NATIONAL_TEAM_PLAYERS INTEGER,
    STADIUM_NAME VARCHAR(255),
    STADIUM_SEATS INTEGER,
    NET_TRANSFER_RECORD VARCHAR(50),
    COACH_NAME VARCHAR(255),
    LAST_SEASON INTEGER,
    URL VARCHAR(500),
    DW_INSERT_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
COMMENT = 'Landing table for Transfermarkt club details';

CREATE OR REPLACE STREAM STRM_TM_CLUBS ON TABLE STG_TM_CLUBS;
