USE SCHEMA LIONS_DB.STAGING;

CREATE TABLE IF NOT EXISTS STG_TM_PLAYERS (
    PLAYER_ID INTEGER,
    FIRST_NAME VARCHAR(255),
    LAST_NAME VARCHAR(255),
    NAME VARCHAR(255),
    LAST_SEASON INTEGER,
    CURRENT_CLUB_ID INTEGER,
    PLAYER_CODE VARCHAR(100),
    COUNTRY_OF_BIRTH VARCHAR(100),
    CITY_OF_BIRTH VARCHAR(255),
    COUNTRY_OF_CITIZENSHIP VARCHAR(100),
    DATE_OF_BIRTH DATE,
    SUB_POSITION VARCHAR(50),
    POSITION VARCHAR(50),
    FOOT VARCHAR(20),
    HEIGHT_IN_CM INTEGER,
    CONTRACT_EXPIRATION_DATE DATE,
    AGENT_NAME VARCHAR(255),
    IMAGE_URL VARCHAR(500),
    URL VARCHAR(500),
    CURRENT_CLUB_DOMESTIC_COMPETITION_ID VARCHAR(20),
    CURRENT_CLUB_NAME VARCHAR(255),
    MARKET_VALUE_IN_EUR INTEGER,
    HIGHEST_MARKET_VALUE_IN_EUR INTEGER,
    DW_INSERT_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
COMMENT = 'Landing table for Transfermarkt player profiles';

CREATE OR REPLACE STREAM STRM_TM_PLAYERS ON TABLE STG_TM_PLAYERS;
