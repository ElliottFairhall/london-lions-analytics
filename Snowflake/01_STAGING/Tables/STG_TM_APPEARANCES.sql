USE SCHEMA LIONS_DB.STAGING;

CREATE TABLE IF NOT EXISTS STG_TM_APPEARANCES (
    APPEARANCE_ID VARCHAR(50),
    GAME_ID INTEGER,
    PLAYER_ID INTEGER,
    PLAYER_CLUB_ID INTEGER,
    PLAYER_CURRENT_CLUB_ID INTEGER,
    DATE DATE,
    PLAYER_NAME VARCHAR(255),
    COMPETITION_ID VARCHAR(20),
    YELLOW_CARDS INTEGER,
    RED_CARDS INTEGER,
    GOALS INTEGER,
    ASSISTS INTEGER,
    MINUTES_PLAYED INTEGER,
    DW_INSERT_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
COMMENT = 'Landing table for match-level player performance';

CREATE OR REPLACE STREAM STRM_TM_APPEARANCES ON TABLE STG_TM_APPEARANCES;
